#!/usr/bin/env python3
"""Generate the C byte-array header for the SCPFS stdio watch helper."""

from __future__ import annotations

import argparse
from pathlib import Path


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()
    data = args.input.read_bytes()
    if not data or len(data) > 256 * 1024:
        raise SystemExit("watch helper must be between 1 and 262144 bytes")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    rows = []
    for offset in range(0, len(data), 16):
        rows.append("\t" + ", ".join(f"0x{byte:02x}" for byte in data[offset:offset + 16]) + ",")
    content = (
        "/* Generated by scripts/embed-watch.py; do not edit. */\n"
        "#ifndef SCPFS_WATCH_EMBEDDED_H\n#define SCPFS_WATCH_EMBEDDED_H\n"
        "static const unsigned char SCPFS_WATCH_HELPER_SOURCE[] = {\n"
        + "\n".join(rows)
        + "\n};\n"
        f"#define SCPFS_WATCH_HELPER_SOURCE_LENGTH {len(data)}u\n"
        "#endif\n"
    )
    args.output.write_text(content, encoding="ascii", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
